SELECT 
    SEASON, 
    WEEK,
    GAME_ID,
    PLAYER_DISPLAY_NAME,
    POSITION,
    TEAM,
    OPPONENT_TEAM,
    FANTASY_POINTS_PPR,

    CASE WHEN RUSHING_YARDS   >=100 THEN 3 ELSE 0 END AS RUNNING_BONUS,
    CASE WHEN RECEIVING_YARDS >=100 THEN 3 ELSE 0 END AS RECIEVING_BONUS,
    CASE WHEN PASSING_YARDS   >=300 THEN 3 ELSE 0 END AS PASSING_BONUS,

    FANTASY_POINTS_PPR
        + CASE WHEN RUSHING_YARDS >= 100 THEN 3 ELSE 0 END
        + CASE WHEN RECEIVING_YARDS >= 100 THEN 3 ELSE 0 END
        + CASE WHEN PASSING_YARDS >= 300 THEN 3 ELSE 0 END
        AS DRAFT_KINGS_POINTS
FROM
{{ source('raw','weekly_player_stats') }}
WHERE POSITION IN ('QB','RB','WR','TE')